#Requires -Version 5.1
<#
  anotherme rule sync -- all logic lives here because the two remaining
  targets need text surgery that batch cannot do safely:

    .codebuddy  *.mdc   keep the IDE-managed frontmatter (enabled /
                        updatedAt / provider), replace only the body
    .claude     CLAUDE.md  regenerate the whole file with an
                        auto-generated marker on the first line

  Invoked by scripts\sync-rules.bat; the CLI options mirror the other
  .bat scripts so usage stays identical.

  NOTE: keep this file pure ASCII. Windows PowerShell 5.1 reads .ps1
  files as ANSI unless they carry a BOM, so non-ASCII literals would
  break on some machines.
#>
param(
    [Parameter(ValueFromRemainingArguments = $true)][string[]]$CliArgs
)

$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = [Text.Encoding]::UTF8

$only = ''
$check = $false
$force = $false

foreach ($a in @($CliArgs)) {
    if ($null -eq $a) { continue }
    if ($a -eq '--check') { $check = $true }
    elseif ($a -eq '--force') { $force = $true }
    elseif ($a -like '--only=*') { $only = $a.Substring(7) }
    elseif ($a -eq '--help' -or $a -eq '-h' -or $a -eq '/?') {
        Write-Host 'anotherme rule sync'
        Write-Host 'Usage: sync-rules.bat [--only=codebuddy|qoder|qodercn|claude] [--check] [--force]'
        Write-Host ''
        Write-Host '  --only=IDE  target a single IDE'
        Write-Host '  --check     report drift only, write nothing'
        Write-Host '  --force     overwrite CLAUDE.md even if it holds foreign content'
        exit 0
    }
    else { Write-Host "[WARN] unknown argument: $a" }
}

$repo = Split-Path -Parent $PSScriptRoot
$src = Join-Path (Join-Path $repo 'docs') 'common_rule.md'
if (-not (Test-Path -LiteralPath $src)) {
    Write-Host "[ERROR] rule source not found: $src"
    exit 1
}

$enc = New-Object System.Text.UTF8Encoding($false)
$marker = '<!-- auto-generated from anotherme/docs/common_rule.md; do not edit this file -->'

$updated = 0
$same = 0
$skipped = 0
$drift = 0

function Read-Utf8([string]$path) {
    $t = [IO.File]::ReadAllText($path, [Text.Encoding]::UTF8)
    if ($t.Length -gt 0 -and $t[0] -eq [char]0xFEFF) { $t = $t.Substring(1) }
    return $t
}
function Write-Utf8([string]$path, [string]$text) {
    [IO.File]::WriteAllText($path, $text, $script:enc)
}
function Norm([string]$t) {
    # Compare on non-blank lines only: the .mdc keeps a blank line after its
    # frontmatter, so a strict compare would report "out of date" forever.
    $lines = ($t -replace "`r`n", "`n") -split "`n"
    return (($lines | Where-Object { $_.Trim() -ne '' }) -join "`n").Trim()
}
function In-Scope([string]$name) {
    return ($script:only -eq '' -or $script:only -eq $name)
}

# ---- source: split frontmatter from body -------------------------------
$raw = Read-Utf8 $src
$fm = [regex]::Match($raw, '(?s)^---\r?\n.*?\r?\n---\r?\n')
if ($fm.Success) { $body = $raw.Substring($fm.Length) } else { $body = $raw }
$nl = $(if ($raw.Contains("`r`n")) { "`r`n" } else { "`n" })
$bodyNorm = Norm $body

Write-Host "Rule source: $src"
Write-Host ''

# ---- qoder / qoder-cn: frontmatter matches the source, full copy ------
function Sync-Copy([string]$name, [string]$dest) {
    if (-not (In-Scope $name)) { return }
    $dir = Split-Path -Parent $dest
    if (-not (Test-Path -LiteralPath $dir)) {
        # same rule as install.bat: create the leaf dir when the IDE root exists
        $parent = Split-Path -Parent $dir
        if (-not (Test-Path -LiteralPath $parent)) {
            Write-Host "[$name] rules dir not found, skipped: $dir"
            $script:skipped++
            return
        }
        if ($script:check) {
            Write-Host "[$name] rules dir missing, would be created: $dir"
            $script:drift++
            return
        }
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }
    if (-not (Test-Path -LiteralPath $dest)) {
        if ($script:check) {
            Write-Host "[$name] MISSING: $dest"
            $script:drift++
            return
        }
        Write-Utf8 $dest $raw
        Write-Host "[$name] created: $dest"
        $script:updated++
        return
    }
    $cur = Read-Utf8 $dest
    if ((Norm $cur) -eq (Norm $raw)) {
        Write-Host "[$name] up to date"
        $script:same++
        return
    }
    if ($script:check) {
        Write-Host "[$name] OUT OF DATE: $dest"
        $script:drift++
        return
    }
    Write-Utf8 $dest $raw
    Write-Host "[$name] updated: $dest"
    $script:updated++
}

# ---- codebuddy: keep the IDE frontmatter, replace the body ------------
# The .mdc filename is IDE-managed and may be localized, so the rule file
# is identified by an ASCII token from the gate table instead of by name.
function Sync-Mdc() {
    if (-not (In-Scope 'codebuddy')) { return }
    $dir = Join-Path $env:USERPROFILE '.codebuddy\rules'
    if (-not (Test-Path -LiteralPath $dir)) {
        Write-Host "[codebuddy] rules dir not found, skipped: $dir"
        $script:skipped++
        return
    }
    $hits = @(Get-ChildItem -LiteralPath $dir -Filter '*.mdc' -File -ErrorAction SilentlyContinue |
              Where-Object { (Norm (Read-Utf8 $_.FullName)) -match 'springboot-spec' })
    if ($hits.Count -eq 0) {
        Write-Host "[codebuddy] no .mdc carrying the gate table found in $dir"
        Write-Host '           skipped -- create the rule once in CodeBuddy, this script keeps it in sync after that'
        $script:skipped++
        return
    }
    foreach ($f in $hits) {
        $cur = Read-Utf8 $f.FullName
        $h = [regex]::Match($cur, '(?s)^---\r?\n.*?\r?\n---\r?\n')
        if ($h.Success) { $head = $h.Value }
        else { $head = "---${nl}description: ${nl}alwaysApply: true${nl}enabled: true${nl}provider: ${nl}---${nl}" }
        $want = $head + $nl + $body
        if ((Norm $cur) -eq (Norm $want)) {
            Write-Host "[codebuddy] up to date: $($f.Name)"
            $script:same++
            continue
        }
        if ($script:check) {
            Write-Host "[codebuddy] OUT OF DATE: $($f.Name)"
            $script:drift++
            continue
        }
        Write-Utf8 $f.FullName $want
        Write-Host "[codebuddy] updated: $($f.Name) (frontmatter preserved)"
        $script:updated++
    }
}

# ---- claude: whole file is ours, guarded by a marker ------------------
function Sync-Claude() {
    if (-not (In-Scope 'claude')) { return }
    $dest = Join-Path $env:USERPROFILE '.claude\CLAUDE.md'
    $dir = Split-Path -Parent $dest
    if (-not (Test-Path -LiteralPath $dir)) {
        Write-Host "[claude] dir not found, skipped: $dir"
        $script:skipped++
        return
    }
    $want = $marker + $nl + $body
    if (-not (Test-Path -LiteralPath $dest)) {
        if ($script:check) {
            Write-Host "[claude] MISSING: $dest"
            $script:drift++
            return
        }
        Write-Utf8 $dest $want
        Write-Host "[claude] created: $dest"
        $script:updated++
        return
    }
    $cur = Read-Utf8 $dest
    if ((Norm $cur) -eq (Norm $want)) {
        Write-Host '[claude] up to date'
        $script:same++
        return
    }
    if ($script:check) {
        Write-Host "[claude] OUT OF DATE: $dest"
        $script:drift++
        return
    }
    # A file already carrying the marker, or holding nothing but a bare copy
    # of the rule (the only place these skill names appear), is ours to
    # rewrite. Anything else may be real memory content -- refuse by default.
    $isOurs = $cur.Contains($marker) -or ((Norm $cur) -match 'solution-design')
    if (-not $isOurs -and -not $script:force) {
        Write-Host "[claude] REFUSED: $dest holds content this script did not generate"
        Write-Host '         re-run with --force to overwrite it, or move that content elsewhere first'
        $script:skipped++
        return
    }
    Write-Utf8 $dest $want
    Write-Host "[claude] updated: $dest"
    $script:updated++
}

Sync-Copy 'qoder' (Join-Path $env:USERPROFILE '.qoder\rules\common_rule.md')
Sync-Copy 'qodercn' (Join-Path $env:USERPROFILE '.qoder-cn\rules\common_rule.md')
Sync-Mdc
Sync-Claude

Write-Host ''
Write-Host '================== Rule sync =================='
Write-Host "Updated: $updated    Up-to-date: $same    Skipped: $skipped"
if ($check -and $drift -gt 0) {
    Write-Host ''
    Write-Host "[CHECK] $drift target(s) out of date. Run without --check to write."
    exit 1
}
exit 0
